/*
 * butler-turnstile.exe: the Turnstile check in WebView2 (native/turnstile). The SDK is a NuGet
 * package, which is a zip; MSVC builds the helper into the app's resources.
 */
val webView2Version = "1.0.4258.31"
val webView2Sdk = layout.buildDirectory.dir("webview2")
val fetchWebView2 by tasks.registering {
    outputs.dir(webView2Sdk)
    doLast {
        val dir = webView2Sdk.get().asFile
        if (dir.resolve("build/native/include/WebView2.h").isFile) return@doLast
        val zip = layout.buildDirectory.file("webview2.zip").get().asFile
        uri("https://www.nuget.org/api/v2/package/Microsoft.Web.WebView2/$webView2Version").toURL()
            .openStream().use { input -> zip.outputStream().use { input.copyTo(it) } }
        copy { from(zipTree(zip)); into(dir) }
    }
}
val appResources = layout.buildDirectory.dir("appResources")
val buildTurnstile by tasks.registering(Exec::class) {
    dependsOn(fetchWebView2)
    val source = file("native/turnstile")
    val out = appResources.get().asFile.resolve("windows")
    inputs.dir(source)
    outputs.file(out.resolve("butler-turnstile.exe"))
    commandLine("cmd", "/c", source.resolve("build.cmd").path, webView2Sdk.get().asFile.path, out.path)
}
tasks.matching { it.name == "prepareAppResources" }.configureEach { dependsOn(buildTurnstile) }

// Supabase's auth module carries Ktor's web server, for an OAuth flow that catches the
// redirect on localhost. Butler passes its own janitor: redirect, and then the module only
// opens the browser (it starts the server only when no redirect is given). The server
// brought full Kotlin reflection with it, and with that on the classpath every typeOf<T>()
// (Ktor runs one per request it decodes) builds heavyweight reflection objects: 860 more
// classes loaded, more start-up work, more memory. None of the three is needed.
