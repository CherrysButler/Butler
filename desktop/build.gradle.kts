compose.desktop {
    application {
        mainClass = "com.cherry.butler.desktop.MainKt"
        // The JVM would otherwise let the heap grow to a quarter of the machine's RAM. Capped,
        // with a collector sized for one window, Butler stays in the low hundreds of MB.
        // The heap is capped so a long session can't grow without bound. (A small starting heap
        // that grows and shrinks was tried and stuttered: collections came far too often.)
        // The collector is Shenandoah, which does its work alongside the app: the serial one
        // stopped everything for 30 ms per collection and 110 ms for a full one while Browse
        // scrolled, which at 180 Hz is 5 to 20 frames lost each time. Shenandoah's pauses are
        // under a millisecond. Left alone it holds the whole 256 MB from the start while about 50
        // is in use; it starts small here, gives back what it hasn't touched for 5 s, and runs a
        // quiet cycle at least every 20 s, which also frees the pictures Skia holds outside the
        // heap for objects no longer in use.
        // Java's quick compiler only (C1). The optimising one (C2) spent 30 s of CPU in the first
        // 20 s compiling Butler and held up to 90 MB doing it; frames are well inside budget on
        // C1's code (measured the same, 0.7 ms at p95 while scrolling at 180 Hz), so C2 bought
        // nothing but a hot, heavy start. Measured: start 32 s of CPU to 14, 637 MB to 547.
        // Java2D (AWT's own drawing) would open a Direct3D device of its own next to Skia's,
        // for nothing: every pixel of Butler is Skia's. Off, it saves ~25 MB and ~20 threads.
        jvmArgs += listOf(
            "-Dsun.java2d.d3d=false",
            "-XX:TieredStopAtLevel=1",
            "-Xms48m", "-Xmx256m", "-XX:+UseShenandoahGC", "-XX:+UnlockExperimentalVMOptions",
            "-XX:ShenandoahUncommitDelay=5000", "-XX:ShenandoahGuaranteedGCInterval=20000",
            // Collect early rather than grow: a quick scroll made the heap swell to ~170 MB
            // (peak 580 MB for Butler) before handing it back. At 96 MB the collector starts
            // sooner, in the background: peak 438 MB, the same CPU, frames unchanged.
            "-XX:SoftMaxHeapSize=96m",
        )
        nativeDistributions {
            appResourcesRootDir.set(appResources)
            // From suggestRuntimeModules, plus what's reached by reflection: TLS's EC ciphers,
            // OkHttp's logging, DNS names, charsets.
            modules(
                "java.instrument", "java.management", "java.prefs", "jdk.unsupported",
                "jdk.crypto.ec", "java.naming", "java.logging", "java.sql", "jdk.charsets",
                // Flight Recorder, for the frame log's trace (FrameLog).
                "jdk.jfr",
            )
            targetFormats(TargetFormat.Msi, TargetFormat.Exe)
            packageName = "Butler"
            packageVersion = "0.4.2"
            vendor = "Cherry"
            windows {
                menu = true
                shortcut = true
                perUserInstall = true
            }
        }
    }
}

// The bundled Java comes without a class-data sharing archive (jlink leaves it out), so every
// launch parsed and verified thousands of Java's own classes from scratch. Once the app is
// assembled, its own launcher runs once with -Xshare:dump to write one into its runtime, where
// Java picks it up by itself. Measured: start 14 s of CPU to 7, and ~60 MB less memory. The
// staging runtime gets a copy, so an installer packaged afterwards carries it too.
val generateCdsArchive by tasks.registering {
    val appDir = layout.buildDirectory.dir("compose/binaries/main/app/Butler")
    val stagingServer = layout.buildDirectory.dir("compose/tmp/main/runtime/bin/server")
    doLast {
        val root = appDir.get().asFile
        val cfg = root.resolve("app/Butler.cfg")
        val original = cfg.readText()
        val nl = System.lineSeparator()
        try {
            cfg.writeText(
                original.replace(
                    "java-options=-Dskiko.library.path",
                    "java-options=-Xshare:dump${nl}java-options=-XX:SharedArchiveFile=\$APPDIR\\..\\runtime\\bin\\server\\classes.jsa${nl}java-options=-Dskiko.library.path",
                ),
            )
            val dump = ProcessBuilder(root.resolve("Butler.exe").absolutePath).redirectErrorStream(true).start()
            dump.inputStream.readBytes()
            check(dump.waitFor() == 0) { "Class-data sharing dump failed" }
        } finally {
            cfg.writeText(original)
        }
        val archive = root.resolve("runtime/bin/server/classes.jsa")
        check(archive.isFile) { "No class-data sharing archive was written" }
        stagingServer.get().asFile.takeIf { it.isDirectory }?.let { archive.copyTo(it.resolve("classes.jsa"), overwrite = true) }
    }
}
tasks.matching { it.name == "createDistributable" }.configureEach { finalizedBy(generateCdsArchive) }

// Windows' newer allocator (the segment heap, which Edge and Windows' own apps use) for
// everything Butler allocates outside Java: Skia, the GPU driver, SQLite. It fragments far
// less than the old one. Opted into from the launcher's manifest, as Windows asks; measured
// ~30 MB less in memory and ~40 MB less committed. Needs the Windows SDK's mt.exe.
val useSegmentHeap by tasks.registering {
    val exe = layout.buildDirectory.file("compose/binaries/main/app/Butler/Butler.exe")
    val work = layout.buildDirectory.dir("tmp/segmentHeap")
    doLast {
        val mt = File("C:/Program Files (x86)/Windows Kits/10/bin").listFiles().orEmpty()
            .sortedByDescending { it.name }
            .map { it.resolve("x64/mt.exe") }
            .firstOrNull { it.isFile }
        if (mt == null) {
            logger.warn("mt.exe not found (Windows SDK): Butler.exe keeps the default heap")
            return@doLast
        }
        val launcher = exe.get().asFile
        launcher.setWritable(true)
        val dir = work.get().asFile.apply { mkdirs() }
        val manifest = dir.resolve("Butler.manifest")
        fun run(vararg args: String) {
            val p = ProcessBuilder(mt.absolutePath, "-nologo", *args).redirectErrorStream(true).start()
            val out = p.inputStream.readBytes().decodeToString()
            check(p.waitFor() == 0) { "mt.exe failed: $out" }
        }
        run("-inputresource:${launcher.absolutePath};#1", "-out:${manifest.absolutePath}")
        val text = manifest.readText()
        if ("SegmentHeap" in text) return@doLast
        manifest.writeText(
            text.replace(
                "</asmv3:windowsSettings>",
                "<heapType xmlns=\"http://schemas.microsoft.com/SMI/2020/WindowsSettings\">SegmentHeap</heapType></asmv3:windowsSettings>",
            ),
        )
        check("SegmentHeap" in manifest.readText()) { "The launcher's manifest had no windowsSettings to add the heap to" }
        run("-manifest", manifest.absolutePath, "-outputresource:${launcher.absolutePath};#1")
    }
}
tasks.matching { it.name == "createDistributable" }.configureEach { finalizedBy(useSegmentHeap) }
generateCdsArchive { mustRunAfter(useSegmentHeap) }
