/*
 * Android's R, generated from app/src/main/res: drawables and fonts become ids that name
 * their file on the classpath, strings their text. The files themselves ship as resources.
 */
val appRes = rootProject.file("app/src/main/res")
val generatedR = layout.buildDirectory.dir("generated/androidR")
val generateR by tasks.registering {
    inputs.dir(appRes)
    outputs.dir(generatedR)
    doLast {
        val out = generatedR.get().asFile.resolve("com/cherry/butler/R.kt")
        out.parentFile.mkdirs()
        val paths = mutableListOf<String>()
        val texts = mutableListOf<String>()
        val sb = StringBuilder("package com.cherry.butler\n\n/** Android's R for the desktop build, generated from app/src/main/res. */\n@Suppress(\"ClassName\", \"ObjectPropertyName\")\nobject R {\n")
        for (type in listOf("drawable", "font")) {
            sb.append("    object $type {\n")
            appRes.resolve(type).listFiles()!!.filter { it.isFile }.sortedBy { it.name }.forEach { f ->
                sb.append("        const val ${f.nameWithoutExtension} = ${paths.size}\n")
                paths += "res/$type/${f.name}"
            }
            sb.append("    }\n")
        }
        val strings = Regex("<string name=\"([^\"]+)\"[^>]*>(.*?)</string>", RegexOption.DOT_MATCHES_ALL)
            .findAll(appRes.resolve("values/strings.xml").readText())
        sb.append("    object string {\n")
        strings.forEach { m ->
            sb.append("        const val ${m.groupValues[1]} = ${1_000_000 + texts.size}\n")
            texts += m.groupValues[2].replace("\\'", "'")
        }
        sb.append("    }\n")
        fun lit(s: String) = "\"" + s.replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$") + "\""
        sb.append("    private val paths = arrayOf(${paths.joinToString { lit(it) }})\n")
        sb.append("    private val texts = arrayOf(${texts.joinToString { lit(it) }})\n")
        sb.append("    fun path(id: Int): String = paths[id]\n")
        sb.append("    fun text(id: Int): String = texts[id - 1_000_000]\n}\n")
        out.writeText(sb.toString())
    }
}

/*
 * Hilt finds every @HiltViewModel by itself; plain Dagger needs them listed. This writes the
 * list from the shared sources, so a new view model on Android is on the desktop too.
 */
val generatedViewModels = layout.buildDirectory.dir("generated/viewModels")
val generateViewModelBindings by tasks.registering {
    inputs.dir(shared)
    outputs.dir(generatedViewModels)
    doLast {
        val packageLine = Regex("""^package ([\w.]+)""", RegexOption.MULTILINE)
        val annotated = Regex("""@HiltViewModel\s+class (\w+)""")
        val found = shared.walkTopDown().filter { it.extension == "kt" }.flatMap { f ->
            val text = f.readText()
            val pkg = packageLine.find(text)?.groupValues?.get(1) ?: return@flatMap emptySequence()
            annotated.findAll(text).map { "$pkg.${it.groupValues[1]}" }
        }.sorted().toList()
        val out = generatedViewModels.get().asFile.resolve("com/cherry/butler/desktop/ViewModelBindings.kt")
        out.parentFile.mkdirs()
        out.writeText(buildString {
            appendLine("package com.cherry.butler.desktop")
            appendLine()
            appendLine("/** Every @HiltViewModel in the shared code, generated by desktop/build.gradle.kts. */")
            appendLine("@dagger.Module")
            appendLine("abstract class ViewModelBindings {")
            found.forEachIndexed { i, cls ->
                appendLine("    @dagger.Binds @dagger.multibindings.IntoMap @dagger.multibindings.ClassKey($cls::class)")
                appendLine("    abstract fun vm$i(vm: $cls): androidx.lifecycle.ViewModel")
            }
            appendLine("}")
        })
    }
}

/*
 * The shared Kotlin, minus the Android-only files, synced into the build. A copy rather than
 * an exclude filter because KSP (Dagger, Room) reads source folders whole.
 */
val sharedSources by tasks.registering(Sync::class) {
    from(shared) {
        exclude(androidOnly.map { "com/cherry/butler/$it" })
        // Android loads res/font fonts by id; the desktop's ButlerFont loads the bundled file.
        filesMatching("com/cherry/butler/core/design/Type.kt") {
            filter { line -> line.replace(Regex("""\bFont\("""), "ButlerFont(") }
        }
    }
    from(rootProject.file("app/src/release/java")) { include("com/cherry/butler/core/auth/**") }
    into(layout.buildDirectory.dir("sharedSrc"))
}

